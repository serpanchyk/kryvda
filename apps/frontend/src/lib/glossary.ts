export type GlossaryGroup = keyof typeof glossary;

/** Map of API values to visible labels for one glossary group. */
export function labelsOf<G extends GlossaryGroup>(group: G): Record<keyof (typeof glossary)[G] & string, string> {
  return Object.fromEntries(
    Object.entries(glossary[group] as Record<string, Term>).map(([key, term]) => [key, term.label]),
  ) as Record<keyof (typeof glossary)[G] & string, string>;
}

/** Look up a term by group and API value; unknown values fall back to the raw value. */
export function termOf(group: GlossaryGroup, key: string): Term {
  return (glossary[group] as Record<string, Term>)[key] ?? { label: key };
}

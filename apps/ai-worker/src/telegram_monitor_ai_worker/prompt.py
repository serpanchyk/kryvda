TARGET_PROMPT = f"""{COMMON}

Завдання: для кожного твердження (claim_id) визнач, кого джерело твердження (claim_source)
КРИТИКУЄ — звинувачує, висміює, натякає на провину, — і кого ПІДТРИМУЄ — хвалить, захищає,
подає у вигідному світлі.
Оцінка може бути прямою або через сарказм, ярлик, лапки-іронію, риторичне питання, а також
через людей, протеже чи колишніх працівників актора, поданих проти нього: «детектив НАБУ просив
продати коноплю», «ексдетектив НАБУ за дивним збігом працює в безпеці Укрзалізниці» — критикують
НАБУ; «ЦПК Шабуніна відбілює корупцію» — критикують ЦПК і Шабуніна.

actors — усі актори твердження. Обирай саме того, кого оцінюють: якщо критикують суддю, а не її
суд, обери суддю; якщо оцінюють когось, кого немає в переліку, обери «інший актор або ніхто з
переліку». Актор НЕ оцінюється, якщо він лише:
- стоїть поруч із чужою негативною подією чи злочином («уникнув служби в ЗСУ»);
- жертва або об'єкт дій інших («впливала на суддів ВАКС»);
- фігурує в нейтральній новині про розслідування, підозру, затримання чи рішення («ДБР
  зареєструвало провадження»), якщо джерело цього не оцінює;
- сам є джерелом і говорить про інших.
Успіхи, результати, висока довіра, отримана допомога чи вигідне подання актора — це підтримка.

У полемічних постах розрізняй сторони. Критикують того, проти кого спрямоване звинувачення;
жертва, захищений актор чи той, хто викрив або затримав злочинців, — не критикований
(«СБУ ліквідувала кілера; зловмисники стежили за військовими» — критикують зловмисників, СБУ
підтримують; «потреби ЗСУ їх не хвилювали» — критикують «їх», ЗСУ не критикують). Якщо канал
наводить чуже звинувачення, щоб його спростувати чи висміяти, обвинуваченого не критикують.

В одному твердженні може бути кілька сторін («ВАКС почав реагувати на провокації хабарів з боку
САП і НАБУ» — ВАКС підтримують, САП і НАБУ критикують; «НАБУ відбілює ЦПК» — критикують обох).

Для кожного claim_id спершу в reason коротко назви, кого джерело критикує і кого підтримує, потім
criticized і supported — імена з actors; порожні списки, якщо джерело нікого не оцінює."""


CANDIDATE_PROMPT = f"""{COMMON}

Завдання: кожен кандидат — особа, орган чи організація з реєстру (name, type), чию назву знайдено
в пості за словниковим збігом; mentions — знайдені форми, contexts — речення поста, де вони
стоять. Для кожного candidate_id визнач, чи mentions у цих реченнях означають саме цю особу чи
організацію з реєстру.

Майже завжди збіг правильний: абревіатура, прізвище, скорочення, посада чи відмінкова форма
назви — це той самий кандидат. Збіг випадковий лише тоді, коли форма означає інше: звичайне
слово («голос народу», «чесно кажучи», «чесні вибори»), інша людина чи організація з такою самою
назвою («Чесна мобілізація» не є Рухом ЧЕСНО), іноземний орган («Міноборони рф»), назва фонду,
проєкту чи кампанії («Янгол ЗСУ»). Вирішуй за змістом речення, а не за великими літерами.

Для кожного кандидата спершу в reason коротко назви, кого чи що означає згадка в реченні, потім
same_actor: true — це той самий кандидат, false — випадковий збіг. Якщо сумніваєшся, став
true."""

ENTITY_PROMPT = f"""{COMMON}

Завдання: знайди конкретних названих акторів (людей, органи, організації, медіа), які діють,
оцінюються або говорять у пості. Один об'єкт — один актор. mentions містить унікальні текстові
форми, а не кожне повторення форми в пості. Ніколи не повторюй той самий рядок усередині одного
entity. Кожен рядок mentions дослівно копіюй із одного неперервного фрагмента поста без
нормалізації; не конструюй mention, поєднуючи розділені фрагменти, і не включай у mention речення
чи цитати. Групуй форми лише коли впевнений, що це той самий актор; якщо не впевнений, залиш їх у
різних entities.

Іноземні органи — окремі актори: «Міноборони рф», «МЗС КНР», «свій генштаб» Путіна не є
українськими відомствами. Назва фонду чи проєкту («Янгол ЗСУ») не є згадкою ЗСУ. Обов'язково
включай названих мовців і медіа, на яких посилається пост («— Садовий», «пише Bihus.Info»), навіть
якщо вони не моніторингові. Не включай займенники («він», «його», «он», «ему»), неназвані групи
(«джерела», «експерти», «активісти») та загальні слова."""

CLAIM_PROMPT = f"""{COMMON}

Завдання: з'ясуй, що пост каже ПРО monitored entities (monitored=true). Витягни атомарні
твердження, кожне з яких щось каже про дії, якості чи оцінку щонайменше однієї monitored entity.
Використовуй лише передані entity IDs.

- entity_ids — monitored entities, про які щось каже твердження: їхні дії, якості чи оцінку, а
  також їхніх людей, протеже, членів чи колишніх працівників, коли пост використовує цей зв'язок
  проти entity («ексдетектив НАБУ брав хабарі», «протеже Андрія Єрмака», «соратники Порошенка»).
  Не включай entity, яка є лише нейтральним тлом: місце служби, отримувач чи адреса («уникнув
  служби в ЗСУ», «передав ЗСУ РЕБи», «звернувся до Міноборони»).
- Якщо monitored entity лише говорить або є підписом-джерелом новини («— Генштаб», «За словами
  Зеленського, росія готує удар»), а зміст не про неї, — це не твердження про неї. Не включай
  мовця в entity_ids, якщо твердження не про нього.
- Обов'язково витягуй оцінні редакційні твердження, навіть якщо їх виражено ярликом, сарказмом,
  лапками-іронією, риторичним питанням, натяком чи заголовком: «Канал називає НАБУ корупційним
  відомством», «Канал іронізує, що Зеленський виконує обіцянки». Якщо пост критикує, висміює чи
  звинувачує monitored entity, для неї обов'язково має бути таке твердження.
- normalized_text — коротке українське речення, яке зберігає, хто що про кого каже.
- evidence_text — рівно один дослівний неперервний фрагмент поста.

Attribution — хто відповідає за твердження:
- named_entity — твердження сказав названий актор із переданих entities: цитата, «заявив», «за
  словами X», а також новинний формат «…, — X» чи «X:» перед або після фрагмента. source_entity_id
  — ID цього актора.
- external_unnamed — лише явно неназване джерело («джерела повідомляють», «за даними слідства»,
  «за версією правоохоронців»); source_entity_id=null.
- channel_editorial — канал говорить від себе; source_entity_id=null.

Epistemic status: "невпевнене" для підозр, версій, «нібито», «можливо», припущень; "питання" для
питань, зокрема риторичних; інакше "ствердження".

Кожен claim обов'язково поверни з усіма полями в такому порядку: normalized_text, entity_ids,
evidence_text, attribution, epistemic_status. Не завершуй JSON до заповнення epistemic_status.
Усередині attribution спочатку вкажи source_entity_id, потім source_kind."""

TARGET_PROMPT = f"""{COMMON}

Завдання: для кожного твердження (claim_id) визнач, кого з його entities джерело твердження
(claim_source) ОЦІНЮЄ — критикує, звинувачує, висміює, натякає на провину, хвалить, підтримує
чи захищає. Оцінка може бути прямою або через сарказм, ярлик, лапки-іронію, риторичне питання,
а також через людей, протеже чи колишніх працівників entity, поданих проти неї.

Entity НЕ оцінюється, якщо вона лише:
- стоїть поруч із чужою негативною подією, звинуваченням чи злочином («уникнув служби в ЗСУ»,
  «авто для потреб ЗСУ»);
- жертва або об'єкт дій інших («впливала на суддів ВАКС», «рф атакувала літак X»);
- фігурує в нейтральній новині про розслідування, підозру, затримання, обшук чи рішення
  («ДБР зареєструвало провадження», «X отримав підозру»), якщо джерело цього не оцінює;
- сама є джерелом і говорить про себе чи про інших.

Для кожного claim_id спершу в reason коротко назви, кого джерело оцінює і як (або «нікого»),
потім evaluated_entity_ids — лише ID оцінюваних entities цього твердження; порожній список,
якщо джерело нікого з них не оцінює."""

CLASSIFICATION_PROMPT = f"""{COMMON}

Завдання: у кожній переданій парі (claim, TARGET) джерело твердження (claim_source) оцінює
TARGET. Визнач напрям цієї оцінки — stance — і риторику. Класифікуй кожну пару рівно один раз.
source_is_target=true означає, що джерело — сам TARGET.

- "негативне" — джерело критикує, звинувачує, висміює, дискредитує TARGET чи натякає на його
  провину: сарказм, ярлики, лапки-іронія, риторичні питання, інсинуації, люди чи протеже TARGET,
  подані проти нього.
- "позитивне" — джерело хвалить, підтримує, рекомендує чи захищає TARGET, зокрема від
  звинувачень («назвав гідним кандидатом», «історія не підтвердилась»).
- "відсутнє" — лише якщо насправді джерело TARGET не оцінює: нейтральний опис дій чи подій,
  самопрезентація TARGET, результати опитувань.

Rhetoric — лише для "негативне", 0-2 найсильніші явні мітки, інакше []:
"корупція_або_особиста_вигода" (хабарі, збагачення, особистий інтерес);
"злочинна_або_незаконна_поведінка" (злочин, порушення закону);
"делегітимізація" (атака на компетентність, легітимність, незалежність, здатність виконувати
роль); "лицемірство_або_подвійні_стандарти" (чіткий контраст між заявленим і зробленим);
"висміювання_або_особиста_образа" (глузування, сарказм, образа, ярлик);
"зовнішній_контроль_або_нелояльність" (працює на іншу державу чи актора, агент впливу,
нелояльність Україні)."""


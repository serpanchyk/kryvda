INSERT INTO registry_entities (canonical_name, coarse_type, monitored)
SELECT canonical_name, coarse_type, true FROM inference_v3_registry_seed
ON CONFLICT (canonical_name) DO UPDATE
SET coarse_type = EXCLUDED.coarse_type, monitored = true, updated_at = now();

INSERT INTO entity_aliases (entity_id, alias, normalized_alias)
SELECT entity.id,
       trim(alias.value),
       lower(regexp_replace(trim(alias.value), '[[:space:]]+', ' ', 'g'))
FROM inference_v3_registry_seed AS seed
JOIN registry_entities AS entity ON entity.canonical_name = seed.canonical_name
CROSS JOIN LATERAL regexp_split_to_table(seed.canonical_name || '; ' || seed.aliases, ';')
    AS alias(value)
WHERE trim(alias.value) <> ''
ON CONFLICT (normalized_alias) DO NOTHING;

